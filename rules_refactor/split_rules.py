def split_grammar(doc: Doc) -> dict:
    # ---- shared / cores
    shared = doc.slice(r"^## Purpose", r"^# PART B", "shared/00_mode_and_schemas.md")
    write_module("shared/00_mode_and_schemas.md",
                 "DSAT Rules — Purpose, Mode Routing, Output Schemas (grammar v8 Part A)",
                 shared)

    gen_core_parts = [
        doc.slice(r"^# PART B", r"^## B\.3\.0 ", "grammar/generation_core.md"),
        doc.slice(r"^## B\.3\.0 ", r"^## B\.3 Passage", "grammar/generation_core.md"),
        doc.slice(r"^## B\.7 ", r"^## B\.12 ", "grammar/generation_core.md"),
        doc.slice(r"^## B\.13 ", r"^# PART C", "grammar/generation_core.md"),
        doc.slice(r"^# PART E", r"^#+ Reference Quick-Index", "grammar/generation_core.md"),
    ]
    write_module("grammar/generation_core.md",
                 "Grammar Generation Core (B.1–B.2, B.3.0, B.7–B.11, B.13–B.15, Part E)",
                 "\n".join(gen_core_parts))

    ann_core = (
        doc.slice(r"^# PART C", r"^# PART D", "grammar/annotation_core.md")
        + "\n"
        + doc.slice(r"^## D\.4 ", r"^## D\.5 ", "grammar/annotation_core.md")
    )
    write_module("grammar/annotation_core.md",
                 "Grammar Annotation/Ingestion Core (Part C + D.4 decision tree)",
                 ann_core)

    taxonomy = "\n".join([
        doc.slice(r"^# PART D", r"^## D\.4 ", "grammar/taxonomy.md"),
        doc.slice(r"^## D\.5 ", r"^## D\.10 ", "grammar/taxonomy.md"),
    ])
    write_module("grammar/taxonomy.md",
                 "Grammar Taxonomy Reference (D.1–D.3, D.5–D.9)", taxonomy)

    write_module("grammar/future_anatomy.md",
                 "Sentence Anatomy Keys — future Pass-3 span annotation (D.10)",
                 doc.slice(r"^## D\.10 ", r"^#+ Reference Quick-Index",
                           "grammar/future_anatomy.md"))

    write_module("grammar/conditional/transitions.md",
                 "Transition Subtype Vocabulary (B.5) — load only for transition_logic",
                 doc.slice(r"^## B\.5 ", r"^## B\.6 ", "grammar/conditional/transitions.md"))

    notes_body = doc.slice(r"^## B\.6 ", r"^## B\.7 ", "grammar/conditional/notes_synthesis.md")

    # ---- B.12 examples
    b12 = doc.slice(r"^## B\.12 ", r"^## B\.13 ", "grammar/examples")
    for head, block in h3_blocks(b12):
        k = key_of(head)
        if k:
            write_module(f"grammar/examples/{k}.md",
                         f"Worked generation example — {k} (B.12)", block)

    # ---- B.3 per-skill blocks
    b3 = doc.slice(r"^## B\.3 Passage", r"^## B\.4 ", "grammar/skills")
    b4 = doc.slice(r"^## B\.4 ", r"^## B\.5 ", "grammar/skills")

    skills: dict[str, list[str]] = {}
    cross_key_note_text = None
    notes_synth_b3 = None
    for head, block in h3_blocks(b3):
        if CROSS_KEY_NOTE in head:
            cross_key_note_text = block
            continue
        k = key_of(head)
        if k is None:
            raise SystemExit(f"B.3 heading without key: {head!r}")
        if k == NOTES_SYNTH_STEM:
            notes_synth_b3 = block
            continue
        target = GRAMMAR_B3_MERGE.get(k, k)
        skills.setdefault(target, []).append(block)

    for head, block in h3_blocks(b4):
        k = key_of(head)
        if k is None:
            raise SystemExit(f"B.4 heading without key: {head!r}")
        skills.setdefault(k, []).append(
            "## Distractor table (B.4)\n\n" + block.split("\n", 1)[1].lstrip("\n")
        )

    unknown = set(skills) - set(GRAMMAR_ROLE_BY_FOCUS)
    if unknown:
        raise SystemExit(f"B.3/B.4 keys not in role map: {sorted(unknown)}")
    missing_b3 = set(GRAMMAR_ROLE_BY_FOCUS) - set(skills)
    if missing_b3:
        raise SystemExit(f"focus keys with no B.3/B.4 content: {sorted(missing_b3)}")

    for k, parts in skills.items():
        role = GRAMMAR_ROLE_BY_FOCUS[k]
        meta = (f"`grammar_focus_key: {k}` — `grammar_role_key: {role}`\n\n"
                "Load with: shared/00_mode_and_schemas.md, grammar/generation_core.md "
                "(or annotation_core.md), grammar/taxonomy.md, plus conditionals "
                "listed in manifest.json.\n")
        body = meta + "\n" + "\n".join(parts)
        if k in PUNCTUATION_DELIMITER_KEYS and cross_key_note_text:
            body += "\n\n" + cross_key_note_text
        write_module(f"grammar/skills/{k}.md",
                     f"Grammar skill module — {k}", body)

    write_module("grammar/conditional/notes_synthesis.md",
                 "Notes Synthesis Metadata (B.6) — load only for choose_best_notes_synthesis",
                 (notes_synth_b3 or "") + "\n" + notes_body)

    # ---- skips
    doc.mark_skip(r"^#+ Reference Quick-Index", r"^## Appendix V",
                  "quick-index (human navigation aid)")
    doc.mark_skip(r"^## Appendix V", None,
                  "generated VOCAB appendix (validator-side; source = vocabulary/master.json)")

    # ---- manifest entries
    manifest: dict = {"skills": {}}
    for k in sorted(skills):
        cond = []
        if k == "transition_logic":
            cond.append("grammar/conditional/transitions.md")
        entry = {
            "role": GRAMMAR_ROLE_BY_FOCUS[k],
            "generate": ["shared/00_mode_and_schemas.md",
                         "grammar/generation_core.md",
                         "grammar/taxonomy.md",
                         f"grammar/skills/{k}.md", *cond],
            "annotate": ["shared/00_mode_and_schemas.md",
                         "grammar/annotation_core.md",
                         "grammar/taxonomy.md",
                         f"grammar/skills/{k}.md", *cond],
        }
        example = OUT / f"grammar/examples/{k}.md"
        if example.exists():
            entry["generate"].append(f"grammar/examples/{k}.md")
        manifest["skills"][k] = entry
    manifest["stem_type_overrides"] = {
        "choose_best_notes_synthesis": {
            "generate": ["shared/00_mode_and_schemas.md",
                         "grammar/generation_core.md",
                         "grammar/taxonomy.md",
                         "grammar/conditional/notes_synthesis.md"],
            "annotate": ["shared/00_mode_and_schemas.md",
                         "grammar/annotation_core.md",
                         "grammar/taxonomy.md",
                         "grammar/conditional/notes_synthesis.md"],
        }
    }
    manifest["do_not_generate"] = ["affirmative_agreement", "negation"]
    return manifest


