#!/usr/bin/env python3
"""Split the corrected DSAT rules monoliths into composable prompt modules.

Reads:
  rules_agent_dsat_grammar_ingestion_generation_v8.md
  rules_agent_dsat_reading_v3.md

Emits under rules/:
  shared/            modules needed by every call
  grammar/           cores, taxonomy, conditionals, examples, skills/<focus_key>.md
  reading/           cores, style fingerprint, skills/<skill_family>.md
  manifest.json      focus-key/skill-family -> ordered file load set
  split_report.json  line-coverage accounting (every source line assigned or
                     explicitly skipped; unassigned lines are an error)

Design rules:
  - Heading-regex driven; never fixed line numbers.
  - Appendix V (generated VOCAB blocks) and the Reference Quick-Index are
    intentionally excluded from prompt modules: Appendix V is validator-side
    (lockstep with backend/app/models/ontology.py via scripts/gen_vocab.py)
    and duplicates the prose taxonomy as a superset.
  - Idempotent: wipes and regenerates rules/ on each run.
"""
