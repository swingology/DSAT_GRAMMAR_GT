# ---------------------------------------------------------------- utilities


class Doc:
    def __init__(self, path: Path):
        self.path = path
        self.lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        self.assigned = [None] * len(self.lines)  # module name or "SKIP:<why>"

    def find(self, pattern: str, start: int = 0) -> int:
        rx = re.compile(pattern)
        for i in range(start, len(self.lines)):
            if rx.match(self.lines[i]):
                return i
        raise SystemExit(f"{self.path.name}: heading not found: {pattern!r}")

    def slice(self, start_pat: str, end_pat: str | None, module: str,
              start_from: int = 0) -> str:
        """Take [start_pat, end_pat) and mark the lines as assigned."""
        s = self.find(start_pat, start_from)
        e = self.find(end_pat, s + 1) if end_pat else len(self.lines)
        for i in range(s, e):
            if self.assigned[i] is None:
                self.assigned[i] = module
        return "".join(self.lines[s:e])

    def mark_skip(self, start_pat: str, end_pat: str | None, why: str) -> None:
        s = self.find(start_pat)
        e = self.find(end_pat, s + 1) if end_pat else len(self.lines)
        for i in range(s, e):
            if self.assigned[i] is None:
                self.assigned[i] = f"SKIP:{why}"

    def coverage(self) -> dict:
        unassigned = []
        run_start = None
        for i, a in enumerate(self.assigned):
            blank = self.lines[i].strip() == ""
            if a is None and not blank:
                if run_start is None:
                    run_start = i
            else:
                if run_start is not None:
                    unassigned.append([run_start + 1, i])  # 1-based inclusive-ish
                    run_start = None
        if run_start is not None:
            unassigned.append([run_start + 1, len(self.lines)])
        counts: dict[str, int] = {}
        for a in self.assigned:
            if a is not None:
                counts[a] = counts.get(a, 0) + 1
        return {
            "file": self.path.name,
            "total_lines": len(self.lines),
            "unassigned_nonblank_ranges": unassigned,
            "lines_per_module": dict(sorted(counts.items())),
        }


def write_module(rel: str, title: str, body: str) -> None:
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(f"# {title}\n\n{GENERATED_HEADER}{body.rstrip()}\n",
                 encoding="utf-8")


def h3_blocks(text: str) -> list[tuple[str, str]]:
    """Split a section body into (### heading line, block text) pairs."""
    out: list[tuple[str, str]] = []
    cur_head, cur = None, []
    for line in text.splitlines(keepends=True):
        if line.startswith("### "):
            if cur_head is not None:
                out.append((cur_head, "".join(cur)))
            cur_head, cur = line.rstrip("\n"), [line]
        elif cur_head is not None:
            cur.append(line)
    if cur_head is not None:
        out.append((cur_head, "".join(cur)))
    return out


def key_of(heading: str) -> str | None:
    m = re.search(r"`([a-z_]+)`", heading)
    return m.group(1) if m else None


