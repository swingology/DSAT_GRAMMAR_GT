def subsection(doc: Doc, num: str, module: str) -> str:
    """Slice '### <num> ' up to the next ### or ## heading."""
    s = doc.find(rf"^### {re.escape(num)}\b")
    e = s + 1
    while e < len(doc.lines) and not re.match(r"^##+ ", doc.lines[e]):
        e += 1
    for i in range(s, e):
        if doc.assigned[i] is None:
            doc.assigned[i] = module
    return "".join(doc.lines[s:e])


def split_reading(doc: Doc) -> dict:
    core = "\n".join([
        doc.slice(r"^## Purpose", r"^## 7\. ", "reading/core_taxonomy.md"),
        doc.slice(r"^## 8\. ", r"^## 13\. ", "reading/core_taxonomy.md"),
        doc.slice(r"^## 17\. ", r"^## 19\. ", "reading/core_taxonomy.md"),
        doc.slice(r"^## 20\. ", r"^## 21\. ", "reading/core_taxonomy.md"),
    ])
    write_module("reading/core_taxonomy.md",
                 "Reading Core Taxonomy (Purpose, §1–§6, §8–§12, §17–§18, §20)", core)

    write_module("reading/annotation_core.md",
                 "Reading Annotation Core (§21 validator checklist; per-skill "
                 "annotation rules live in skills/)",
                 doc.slice(r"^## 21\. ", r"^## 22\. ", "reading/annotation_core.md"))

    # §16.9 table rows get distributed per family; the rest of §16 + §14 + §15 + §23 = generation core
    sec169 = subsection(doc, "16.9", "reading/skills(16.9)")
    gen_core = "\n".join([
        doc.slice(r"^## 14\. ", r"^## 16\. ", "reading/generation_core.md"),
        doc.slice(r"^## 16\. ", r"^### 16\.9\b", "reading/generation_core.md"),
        doc.slice(r"^## 23\. ", r"^## Appendix V", "reading/generation_core.md"),
    ])
    write_module("reading/generation_core.md",
                 "Reading Generation Core (§14–§16.8, §23)", gen_core)

    write_module("reading/style_fingerprint.md",
                 "Reading Passage Style Fingerprint (§22) — generation only",
                 doc.slice(r"^## 22\. ", r"^## 23\. ", "reading/style_fingerprint.md"))

    # §16.9 rows: header + rows filtered per family
    lines169 = [l for l in sec169.splitlines() if l.strip()]
    table_head = [l for l in lines169 if l.startswith("|")][:2]
    rows = [l for l in lines169 if l.startswith("|")][2:]
    preamble = "\n".join(l for l in lines169 if not l.startswith("|") and not l.startswith("###"))

    # §7 intro (before 7.1) belongs to every fragment's context; slice per family
    manifest: dict = {"skills": {}}
    doc.slice(r"^## 7\. ", r"^### 7\.1\b", "reading/skills(§7 intro)")
    sec7_intro = "".join(doc.lines[doc.find(r"^## 7\. "):doc.find(r"^### 7\.1\b")])
    doc.slice(r"^## 13\. ", r"^### 13\.1\b", "reading/skills(§13 intro)")
    doc.slice(r"^## 19\. ", r"^### 19\.1\b", "reading/skills(§19 intro)")
    doc.slice(r"^### 19\.7\b", r"^## 20\. ", "reading/core_taxonomy.md(19.7 summary)")

    for family, (s7, s13, s19) in READING_FAMILY_SECTIONS.items():
        parts = [sec7_intro, subsection(doc, s7, f"reading/skills/{family}.md"),
                 subsection(doc, s13, f"reading/skills/{family}.md")]
        if s19:
            parts.append(subsection(doc, s19, f"reading/skills/{family}.md"))
        fam_focus = set(READING_FOCUS_BY_FAMILY[family])
        fam_rows = [r for r in rows
                    if (m := re.search(r"`([a-z0-9_]+)`", r)) and m.group(1) in fam_focus]
        if fam_rows:
            parts.append("### Per-focus generation and distractor recipes (§16.9)\n\n"
                         + preamble + "\n\n" + "\n".join(table_head + fam_rows))
        write_module(f"reading/skills/{family}.md",
                     f"Reading skill module — {family}", "\n\n".join(parts))
        manifest["skills"][family] = {
            "focus_keys": READING_FOCUS_BY_FAMILY[family],
            "generate": ["shared/00_mode_and_schemas.md",
                         "reading/core_taxonomy.md",
                         "reading/generation_core.md",
                         "reading/style_fingerprint.md",
                         f"reading/skills/{family}.md"],
            "annotate": ["shared/00_mode_and_schemas.md",
                         "reading/core_taxonomy.md",
                         "reading/annotation_core.md",
                         f"reading/skills/{family}.md"],
        }

    doc.mark_skip(r"^## Appendix V", None,
                  "generated VOCAB appendix (validator-side; source = vocabulary/master.json)")
    # version footer travels with generation core's tail slice already? No — it
    # sits between §23 end and Appendix V, so the §23 slice captured it.
    return manifest


# ---------------------------------------------------------------- main

def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    gdoc, rdoc = Doc(GRAMMAR_SRC), Doc(READING_SRC)
    for d in (gdoc, rdoc):
        d.assigned[0] = "SKIP:source title line"
    manifest = {
        "version": "rules-refactor v1 (grammar v8.2-refactor + reading v3.1-refactor)",
        "grammar": split_grammar(gdoc),
        "reading": split_reading(rdoc),
    }
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    report = {"grammar": gdoc.coverage(), "reading": rdoc.coverage()}
    (OUT / "split_report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    for name, cov in report.items():
        gaps = cov["unassigned_nonblank_ranges"]
        status = "OK" if not gaps else f"UNASSIGNED RANGES: {gaps}"
        print(f"{name}: {cov['total_lines']} lines — {status}")
    n_files = sum(1 for _ in OUT.rglob("*.md"))
    print(f"emitted {n_files} modules under {OUT}")


if __name__ == "__main__":
    main()
